// All configurations below are synthetic temporary fixtures. Never starts MCP servers.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const toml = require('smol-toml');
const { perform } = require('../packages/mcp-manager/mods/mcp-manager/manage.cjs');
const { patchTabs, integrateLayout } = require('../packages/mcp-manager/install.cjs');
const home = fs.mkdtempSync(path.join(os.tmpdir(), 'herdr-mcp-'));
const cwd = path.join(home, 'project'); fs.mkdirSync(cwd);
const put = (file, data) => { fs.mkdirSync(path.dirname(file), { recursive:true }); fs.writeFileSync(file, data); };
const user = path.join(home, '.pi/agent/mcp.json'), project = path.join(cwd, '.pi/mcp.json');
const request = { client:'pi', cwd, action:'list' };
try {
  let view = perform(request, home); assert.deepEqual(view.rows, []);
  put(user, JSON.stringify({ unrelated: 123, mcpServers: { alpha: { command:'NEVER_EXECUTE', env:{ TOKEN:'SECRET_FIXTURE' } }, beta:{ url:'https://invalid.test/mcp',enabled:false }, gamma:{ url:'https://invalid.test/auth',headers:{ Authorization:'Bearer SECRET_FIXTURE' } }, delta:{ url:'ftp://invalid.test/mcp' } } }));
  put(project, JSON.stringify({ mcpServers:{ alpha:{ enabled:false }, unicode:{ command:'NEVER_EXECUTE' } } }));
  view = perform(request, home);
  assert.equal(view.rows.find(r=>r.name==='alpha').scope, 'Proyecto');
  assert.equal(view.rows.find(r=>r.name==='alpha').enabled, false);
  assert.equal(view.rows.find(r=>r.name==='beta').oauth, true, 'Pi remote HTTP servers without Authorization can use Pi OAuth');
  assert.equal(view.rows.find(r=>r.name==='gamma').oauth, false, 'static Authorization headers bypass Pi OAuth');
  assert.equal(view.rows.find(r=>r.name==='alpha').oauth, false);
  assert.equal(view.rows.find(r=>r.name==='delta').oauth, false, 'non-HTTP URLs cannot use Pi OAuth');
  assert.ok(!JSON.stringify(view).includes('https://invalid.test'), 'remote URLs are not exposed to Herdr state');
  assert.ok(!JSON.stringify(view).includes('SECRET_FIXTURE'));
  assert.ok(!JSON.stringify(view).includes('NEVER_EXECUTE'));
  const apply = { ...request, action:'apply', confirmed:true, snapshot:view.snapshot, names:['alpha','beta'], enabled:true };
  assert.throws(()=>perform({ ...apply, confirmed:false },home), /confirmación/);
  assert.throws(()=>perform({ ...apply, snapshot:'stale' },home), /cambiado/);
  assert.throws(()=>perform({ ...apply, names:['missing'] },home), /no disponible/);
  view = perform(apply,home);
  assert.equal(view.backups.length,2);
  assert.equal(JSON.parse(fs.readFileSync(user)).mcpServers.alpha.env.TOKEN, 'SECRET_FIXTURE');
  assert.equal(JSON.parse(fs.readFileSync(user)).unrelated, 123);
  assert.deepEqual(JSON.parse(fs.readFileSync(project)).mcpServers.alpha, { enabled:true });
  assert.ok(view.backups.every(f=>fs.existsSync(f)));
  let before=fs.readFileSync(user,'utf8');
  fs.writeFileSync(user+'.herdr-mcp.lock','');
  assert.throws(()=>perform({ ...apply,snapshot:view.snapshot,names:['beta'],enabled:false },home), /EEXIST/);
  assert.equal(fs.readFileSync(user,'utf8'),before); fs.unlinkSync(user+'.herdr-mcp.lock');
  put(project,'{bad JSON SECRET_FIXTURE');
  assert.throws(()=>perform(request,home), e=>/inválida/.test(e.message)&&!e.message.includes('SECRET_FIXTURE'));
  put(project,'{}');
  const config=path.join(home,'.codex/config.toml');
  put(path.join(cwd,'.git/HEAD'),'ref: refs/heads/test');
  put(config,'# test comment\nmodel = "test"\n[mcp_servers."server.with.dot"]\ncommand = "NEVER_EXECUTE"\n[mcp_servers."server.with.dot".env]\nTOKEN = "SECRET_FIXTURE"\n');
  const codex={ client:'codex',cwd,action:'list' };
  view=perform(codex,home); assert.equal(view.rows[0].name,'server.with.dot');
  perform({ ...codex,action:'apply',confirmed:true,snapshot:view.snapshot,names:['server.with.dot'],enabled:false },home);
  const parsed=toml.parse(fs.readFileSync(config,'utf8'));
  assert.equal(parsed.model,'test'); assert.equal(parsed.mcp_servers['server.with.dot'].enabled,false);
  assert.equal(parsed.mcp_servers['server.with.dot'].env.TOKEN,'SECRET_FIXTURE');
  put(path.join(home,'.claude.json'),'{"mcpServers":{"read-only":{"command":"NEVER_EXECUTE"}}}');
  const claude={client:'claude',cwd,action:'list'};view=perform(claude,home);assert.equal(view.writable,false);
  assert.throws(()=>perform({...claude,action:'apply',confirmed:true,snapshot:view.snapshot,names:['read-only'],enabled:false},home),/solo lectura/);
  assert.throws(()=>perform({...request,client:'unknown'},home),/Contexto/);
  // Synthetic integration anchors; no shipped source is redistributed.
  const tabs='const enabled = shared("workspace.panels") ?? ["files", "changes"];\n.when(enabled.includes("changes"), el => el.child(panelButton("changes", "Changes", "mods/changes/changes.svg")))';
  assert.equal(patchTabs(patchTabs(tabs)),patchTabs(tabs));
  assert.throws(()=>patchTabs('incompatible'),/ancla/);
  const layout={id:'root',children:[{id:'tabs',content:{mod:'custom-quota-tabs'}},{id:'panel-body',type:'stack',children:[]}]};
  assert.equal(integrateLayout(layout).children[1].children[0].content.mod,'mcp-manager');
  assert.throws(()=>integrateLayout({}),/incompatible/);
  console.log('Passed MCP: empty files, Pi precedence, secret redaction, confirmation/stale/lock guards, individual & bulk writes, backups, TOML nested/quoted names, Claude read-only, integration idempotency. No real configuration touched.');
} finally { fs.rmSync(home,{recursive:true,force:true}); }
